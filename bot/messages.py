def format_days_until(days: int) -> str:
    """
    Превращает число дней в человеческую фразу: "сегодня" / "завтра" /
    "через N день/дня/дней" с правильным русским склонением.

    Используется в /all_events для пометки «‼️через N» у самого ближнего
    события (раздел 3.5/4 брифа) и пригодится в /next_event — там та же
    формулировка "через сколько дней" нужна для любого события, не только
    ближайших двух недель.

    Склонение "день/дня/дней" зависит от последней цифры числа, кроме
    диапазона 11–14 (там всегда "дней" — русское исключение из правила):
    1 день, 2/3/4 дня, 5..20 дней, 21 день, 22 дня, 25 дней...
    """
    if days == 0:
        return "сегодня"
    if days == 1:
        return "завтра"

    if 11 <= days % 100 <= 14:
        word = "дней"
    else:
        last_digit = days % 10
        if last_digit == 1:
            word = "день"
        elif 2 <= last_digit <= 4:
            word = "дня"
        else:
            word = "дней"

    return f"через {days} {word}"
