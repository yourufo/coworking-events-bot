"""
Модуль настроек бота.

Все секретные данные (токен бота, выданный BotFather) не должны храниться
прямо в коде — иначе они попадут в git-репозиторий и станут видны всем,
у кого есть доступ к коду. Вместо этого мы кладём их в файл `.env`
(он добавлен в `.gitignore`, то есть в репозиторий не попадает) и читаем
оттуда через библиотеку `python-dotenv`.

Как получить токен бота:
1. Написать в Telegram боту @BotFather
2. Команда /newbot, следовать инструкциям
3. Скопировать `.env.example` в `.env` и вписать туда полученный токен
   (см. `.env.example` в корне проекта)
"""

import os

from dotenv import load_dotenv

# Подгружаем переменные окружения из файла .env, если он есть рядом с проектом.
# Если файла нет — не страшно, просто ничего не подгрузится (например,
# на боевом сервере переменные окружения обычно задают средствами самого
# сервера, а не файлом .env).
load_dotenv()

BOT_TOKEN = os.getenv("BOT_TOKEN")

if not BOT_TOKEN:
    raise RuntimeError(
        "Не найден BOT_TOKEN. Скопируйте .env.example в .env и впишите туда "
        "токен бота, полученный от @BotFather."
    )

# Путь к файлу базы данных SQLite.
# SQLite — это база данных "в одном файле": не нужен отдельный сервер БД,
# не нужна установка и настройка — файл просто лежит на диске рядом с ботом.
# Для одного бота, обслуживающего чаты коворкинга, этого более чем достаточно.
# Если проект сильно вырастет, можно будет перейти на PostgreSQL — структура
# таблиц (см. database.py) при этом не изменится, поменяется только способ
# подключения.
DB_PATH = os.getenv("DB_PATH", "data/coworking.db")
